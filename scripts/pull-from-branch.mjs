// Take translations off the `crowdin` git branch, without merging it.
//
// Run: node scripts/pull-from-branch.mjs   (or `bun run crowdin:pull-branch`)
//
// ## Why this exists alongside `crowdin:pull`
//
// There are two live paths out of Crowdin and they are not equivalent:
//
//   1. The CLI (`crowdin:pull`) talks to the API. It needs CROWDIN_PROJECT_ID and
//      CROWDIN_PERSONAL_TOKEN, which live in CI and in one person's shell.
//   2. Crowdin's GitHub integration, installed on the org, pushes translations to the `crowdin`
//      branch on its own schedule. No credentials involved: the translations are simply in git.
//
// Path 2 is what actually runs day to day, and it means a checkout with no token is still holding
// every translation Crowdin has produced. This script is how you get them.
//
// ## Why it cannot just be `git merge crowdin`
//
// The integration writes that branch as a full picture of what CROWDIN holds, so merging applies
// Crowdin's absences as deletions. Measured against `origin/crowdin` on 2026-08-10, a merge would:
//
//   - delete `locales/en-x-pirate/` and `locales/en-x-piglatin/`, which Crowdin has never heard of
//     because they are generated by scripts/generate-fun-locales.mjs and deliberately ignored;
//   - resurrect `locales/es/`, four files frozen at the branch's initial commit, alongside the live
//     `locales/es-ES/`. The eager glob in index.ts would then ship two competing Spanish catalogs;
//   - roll `locales/en/` — the SOURCE catalog — back to the fork point. The integration has never
//     once written a source file, so that directory on the branch only falls further behind.
//
// So this takes the seven human locale directories by name and nothing else. The allowlist is
// explicit rather than derived: a glob would pick up `es/` the moment it appeared, which is exactly
// the failure it exists to prevent.
//
// ## Why it MERGES instead of replacing, which is the whole subtlety
//
// The branch is not a superset of what is committed here. The first version of this script did the
// obvious thing — check the directories out and prune — and the result was measured at 465 real
// translations gained and **499 lost**. The lost keys were live in the English source, not orphans,
// and the same key names went missing in all seven languages at once, so it is not per-language
// invalidation. The two export paths out of Crowdin simply do not agree: `pull-translations.mjs`
// records that "Skip untranslated strings" governs the GitHub integration but not the CLI, and this
// repo's catalogs were last filled by the CLI.
//
// Neither path is authoritative, so neither gets to delete. A key present on the branch takes the
// branch's value (it is the fresher sync); a key the branch has nothing for keeps what is already
// committed. The result only ever grows, which is the correct failure mode for a translation
// catalog: a missing key falls back to readable English, and no reviewer ever notices a deletion in
// a 100-file diff.

import { spawnSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";

/** The locales Crowdin translates. NOT `en` (source) and NOT `es` (dead). Add here, deliberately. */
const LOCALES = [
	"de-DE",
	"en-GB",
	"es-ES",
	"fr-FR",
	"ja-JP",
	"ko-KR",
	"pt-BR",
];
const BRANCH = process.argv[2] ?? "origin/crowdin";
const ROOT = new URL("../locales", import.meta.url).pathname.replace(
	/^\/([A-Z]:)/,
	"$1",
);

function git(...args) {
	const run = spawnSync("git", args, { encoding: "utf8" });
	if (run.status !== 0) {
		console.error(`git ${args.join(" ")} failed:\n${run.stderr}`);
		process.exit(run.status ?? 1);
	}
	return run.stdout;
}

/**
 * Remove empty-string leaves, and any object left empty by that. Returns the count removed.
 *
 * Crowdin writes `""` for an untranslated string rather than omitting the key, and that difference
 * is the opposite of cosmetic: a MISSING key falls back to English, while an empty string is found,
 * treated as a translation, and rendered as nothing. Shipping the export raw blanks the UI at
 * precisely the places a translation is absent.
 */
function prune(node) {
	let removed = 0;
	for (const [k, v] of Object.entries(node)) {
		if (v && typeof v === "object" && !Array.isArray(v)) {
			removed += prune(v);
			if (Object.keys(v).length === 0) delete node[k];
		} else if (typeof v === "string" && !v.trim()) {
			delete node[k];
			removed += 1;
		}
	}
	return removed;
}

/**
 * Overlay `next` onto `base`, keeping anything `next` has no value for.
 *
 * `next` wins on a conflict because it is the fresher sync. `base` survives everywhere `next` is
 * silent, which is what stops a pull deleting translations the other export path still holds.
 */
function merge(base, next) {
	const out = { ...base };
	for (const [k, v] of Object.entries(next)) {
		if (v && typeof v === "object" && !Array.isArray(v)) {
			const under = out[k];
			out[k] = merge(
				under && typeof under === "object" && !Array.isArray(under) ? under : {},
				v,
			);
		} else {
			out[k] = v;
		}
	}
	return out;
}

/** Stable key order, so a pull produces a reviewable diff rather than a reshuffle. */
function sortDeep(value) {
	if (!value || typeof value !== "object" || Array.isArray(value)) return value;
	return Object.fromEntries(
		Object.keys(value)
			.sort()
			.map((k) => [k, sortDeep(value[k])]),
	);
}

git("fetch", "origin", "--quiet");
const head = git("log", "-1", "--format=%h %ci", BRANCH).trim();
console.log(`${BRANCH} @ ${head}`);

const present = new Set(
	git("ls-tree", "--name-only", BRANCH, "locales/")
		.split("\n")
		.map((l) => l.trim().replace(/^locales\//, ""))
		.filter(Boolean),
);
const take = LOCALES.filter((l) => present.has(l));
const missing = LOCALES.filter((l) => !present.has(l));
if (missing.length) console.log(`not on the branch, skipped: ${missing.join(", ")}`);

/** A namespace as currently COMMITTED, or `{}` if this locale does not have that file yet. */
function committed(locale, ns) {
	const run = spawnSync("git", ["show", `HEAD:locales/${locale}/${ns}`], {
		encoding: "utf8",
	});
	if (run.status !== 0) return {};
	try {
		return JSON.parse(run.stdout);
	} catch {
		return {};
	}
}

/** Every namespace name either side knows about, so a file only one of them has still lands. */
function namespaces(locale) {
	const names = new Set();
	for (const ref of ["HEAD", BRANCH]) {
		for (const line of git("ls-tree", "--name-only", ref, `locales/${locale}/`).split("\n")) {
			const name = line.trim().split("/").pop();
			if (name?.endsWith(".json")) names.add(name);
		}
	}
	return [...names].sort();
}

let removed = 0;
let added = 0;
let files = 0;
/** Namespaces neither side has anything translated for, so no file is written. */
const emptied = [];
for (const locale of take) {
	for (const ns of namespaces(locale)) {
		const path = join(ROOT, locale, ns);
		const incoming = spawnSync(
			"git",
			["show", `${BRANCH}:locales/${locale}/${ns}`],
			{ encoding: "utf8" },
		);
		let fresh = {};
		if (incoming.status === 0) {
			try {
				fresh = JSON.parse(incoming.stdout);
			} catch (e) {
				console.error(`  ! ${BRANCH}:${locale}/${ns} is not valid JSON - ${e.message}`);
				process.exitCode = 1;
				continue;
			}
		}
		// Prune BEFORE merging. An empty string on the branch must not overwrite a real translation
		// already committed here, and `merge` deliberately lets `fresh` win on every key it holds.
		removed += prune(fresh);

		const base = committed(locale, ns);
		const before = JSON.stringify(sortDeep(base));
		const result = merge(base, fresh);
		const after = JSON.stringify(sortDeep(result));

		// Crowdin exports all 16 namespaces for every target language regardless of coverage, so a
		// locale overriding a handful of strings still receives a file per namespace. Once the
		// untranslated entries are stripped most of those are `{}` — and an empty catalog is not
		// neutral: the glob in index.ts loads it and i18next registers an empty namespace.
		if (Object.keys(result).length === 0) {
			if (existsSync(path)) rmSync(path);
			emptied.push(`${locale}/${ns}`);
			continue;
		}
		if (after === before && existsSync(path)) continue;
		if (!existsSync(path)) {
			// A locale can gain a namespace it has never had (marketing.json for six languages here),
			// and the directory itself may not exist on a brand new target language.
			mkdirSync(join(ROOT, locale), { recursive: true });
			added += 1;
		}
		files += 1;
		writeFileSync(path, `${JSON.stringify(sortDeep(result), null, "\t")}\n`);
	}
}

console.log(
	`\nStripped ${removed} empty value(s) from the branch before merging.` +
		`\nWrote ${files} file(s), ${added} of them new.`,
);
if (emptied.length)
	console.log(`Skipped ${emptied.length} catalog(s) with nothing translated on either side.`);
console.log(
	"\nNow: node scripts/generate-fun-locales.mjs && bun run check, then review `git diff`.",
);
